"""Phase 1 ingest: raw CSV + patterns file -> DuckDB.

    uv run python -m scripts.ingest

Builds: transactions, fx_rates, customers, eval.txn_labels, eval.laundering_attempts.
Rebuilds everything on each run, then writes a report block into docs/PROGRESS.md.
"""

import argparse
import logging
import time
from pathlib import Path

import duckdb

from aml.config import get_settings
from aml.data.customers import build_customers
from aml.data.fx import fx_consistency
from aml.data.ingest import build_transactions, check_row_order, drop_raw_lines, load_raw_lines
from aml.data.split import assign_split
from aml.eval.labels import build_txn_labels, laundering_rate_by_split
from aml.eval.patterns import PatternMatchReport, build_laundering_attempts, parse_patterns
from scripts._report import PROGRESS_PATH, write_block

log = logging.getLogger("ingest")


def render_report(
    n_rows: int,
    n_customers: int,
    split_date: str,
    rates: dict[str, dict[str, float]],
    patterns: PatternMatchReport,
    fx: dict[str, float],
) -> str:
    lines = [
        "_Generated by `scripts/ingest.py`; rerunning replaces this block._",
        "",
        f"- Transactions: {n_rows:,}",
        f"- Customers (one per bank+account): {n_customers:,}",
        f"- FX check on {int(fx['rows']):,} cross-currency rows: median |received_usd/paid_usd - 1|"
        f" = {fx['median_rel_err']:.4%}, p95 = {fx['p95_rel_err']:.4%}",
        "",
        f"**Split** (train = before {split_date})",
        "",
        "| split | rows | share | laundering rows | laundering rate |",
        "|---|---:|---:|---:|---:|",
    ]
    for split, r in rates.items():
        lines.append(
            f"| {split} | {r['rows']:,} | {r['rows'] / n_rows:.1%} | {r['laundering']:,} "
            f"| {r['rate']:.4%} |"
        )
    lines += [
        "",
        "**Patterns file match**",
        "",
        f"- Pattern rows matched to txn_ids: {patterns.matched_rows:,} / {patterns.pattern_rows:,}"
        f" ({patterns.match_rate:.2%})",
        f"- Attempts fully matched: {patterns.fully_matched_attempts} / {patterns.attempts}",
        f"- Labeled-laundering rows covered by an attempt: {patterns.positives_covered:,} / "
        f"{patterns.labeled_positive_rows:,} "
        f"({patterns.positives_covered / patterns.labeled_positive_rows:.1%})",
        f"- Matched rows not labeled laundering: {patterns.matched_but_unlabeled}",
        "",
        "| typology | attempts | txns |",
        "|---|---:|---:|",
    ]
    for typ, n in patterns.attempts_by_typology.items():
        lines.append(f"| {typ} | {n} | {patterns.rows_by_typology[typ]} |")
    return "\n".join(lines)


def main() -> None:
    settings = get_settings()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--csv", type=Path, default=settings.transactions_path)
    parser.add_argument("--patterns", type=Path, default=settings.patterns_path)
    parser.add_argument("--db", type=Path, default=settings.duckdb_path)
    parser.add_argument("--no-report", action="store_true", help="don't touch docs/PROGRESS.md")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s", datefmt="%H:%M:%S")

    args.db.parent.mkdir(parents=True, exist_ok=True)
    conn = duckdb.connect(str(args.db))
    t0 = time.perf_counter()

    n_raw = load_raw_lines(conn, args.csv)
    log.info("raw lines: %s", f"{n_raw:,}")
    log.info("row-order spot check: %d lines ok", check_row_order(conn, args.csv))

    n_rows = build_transactions(conn)
    log.info("transactions: %s", f"{n_rows:,}")

    split_counts = assign_split(conn, settings.train_test_split_date)
    log.info("split %s: %s", settings.train_test_split_date, split_counts)

    log.info("labels: %s", f"{build_txn_labels(conn):,}")
    patterns = build_laundering_attempts(conn, parse_patterns(args.patterns))
    log.info(
        "patterns: %d/%d rows matched (%.2f%%), %d/%d attempts complete",
        patterns.matched_rows,
        patterns.pattern_rows,
        100 * patterns.match_rate,
        patterns.fully_matched_attempts,
        patterns.attempts,
    )
    drop_raw_lines(conn)

    n_customers = build_customers(conn, settings.customer_seed)
    log.info("customers: %s", f"{n_customers:,}")

    fx = fx_consistency(conn)
    log.info("fx check: %s", fx)
    rates = laundering_rate_by_split(conn)
    log.info("laundering rate by split: %s", rates)
    conn.close()
    log.info("done in %.0fs", time.perf_counter() - t0)

    if not args.no_report:
        block = render_report(
            n_rows, n_customers, str(settings.train_test_split_date), rates, patterns, fx
        )
        write_block("ingest", block)
        log.info("report written to %s", PROGRESS_PATH)


if __name__ == "__main__":
    main()
