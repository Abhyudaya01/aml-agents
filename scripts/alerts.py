"""Phase 2: features -> anomaly scores -> tune on train -> alerts -> test evaluation.

    uv run python -m scripts.alerts            # tune on train, freeze, evaluate
    uv run python -m scripts.alerts --frozen   # reuse artifacts/thresholds.json as-is

Order matters: thresholds are tuned on the train split, written and hashed BEFORE
any test-split metric is computed, and the test metrics are never fed back.
"""

import argparse
import logging
import time

import duckdb

from aml.alerts.anomaly import fit_and_score
from aml.alerts.features import build_features
from aml.alerts.records import ANOMALY_WEIGHT, RULE_WEIGHT, build_alerts, score_windows
from aml.alerts.rules import RULES, build_rule_hits
from aml.alerts.thresholds import load_thresholds, save_thresholds, thresholds_sha256
from aml.alerts.windows import build_legs
from aml.config import get_settings
from aml.eval.alert_metrics import (
    AlertMetrics,
    RuleBreakdown,
    TypologyRecall,
    build_ablation_alerts,
    build_positive_units,
    evaluate_slice,
    rule_breakdown,
    slice_conditions,
    typology_recall,
)
from aml.eval.tuning import TuningResult, tune_thresholds
from scripts._report import PROGRESS_PATH, write_block

log = logging.getLogger("alerts")


def _fmt(v: float | None) -> str:
    return "disabled" if v is None else f">= {v:g}"


def render_report(
    sha: str,
    tuning: TuningResult | None,
    metrics: list[AlertMetrics],
    typologies: list[TypologyRecall],
    rules: list[RuleBreakdown],
    th_path: str,
) -> str:
    th = load_thresholds(get_settings().thresholds_path)
    w = {r.rule_id: r.weight for r in RULES}
    lines = [
        "_Generated by `scripts/alerts.py`; rerunning replaces this block._",
        "",
        f"Thresholds: `{th_path}` (sha256 `{sha[:12]}`), budget "
        f"{th.budget_per_1k_windows:g} alerts / 1k train account-windows, "
        f"combined-score cutoff {th.alert_threshold:.4f}.",
        "",
        "| rule | weight | threshold |",
        "|---|---:|---|",
        f"| FAN_IN | {w['FAN_IN']} | cp_in {_fmt(th.fan_in_min_cp)} |",
        f"| FAN_OUT | {w['FAN_OUT']} | cp_out {_fmt(th.fan_out_min_cp)} |",
        f"| STRUCTURING | {w['STRUCTURING']} | n_near_threshold {_fmt(th.structuring_min_count)} |",
        f"| VELOCITY_SPIKE | {w['VELOCITY_SPIKE']} | "
        + (
            "disabled"
            if th.velocity_min_24h is None or th.velocity_min_burst is None
            else f"max_24h >= {th.velocity_min_24h:g} and burst_ratio >= {th.velocity_min_burst:g}"
        )
        + " |",
        f"| PASS_THROUGH | {w['PASS_THROUGH']} | n_pass_through "
        f"{_fmt(th.pass_through_min_count)} |",
        "",
        f"combined = {RULE_WEIGHT} x min(1, sum fired weights) + {ANOMALY_WEIGHT} x anomaly pct",
    ]
    if tuning is not None:
        lines += [
            "",
            f"Tuning: {tuning.trials} trials over {tuning.train_windows:,} train windows "
            f"({tuning.train_positive_windows:,} positive); train recall "
            f"{tuning.best.recall:.1%} at precision {tuning.best.precision:.1%}.",
        ]
    lines += [
        "",
        "**Baseline** (train row is in-sample; test rows are the out-of-sample result)",
        "",
        "| variant | slice | alerts | per 1k accts | per 1k windows | precision | recall "
        "| txn recall (cited) | txn recall (window) |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for m in metrics:
        lines.append(
            f"| {m.variant} | {m.slice} | {m.alerts:,} | {m.alerts_per_1k_accounts:.1f} "
            f"| {m.alerts_per_1k_windows:.1f} | {m.precision:.1%} | {m.recall:.1%} "
            f"| {m.txn_recall_cited:.1%} | {m.txn_recall_window:.1%} |"
        )
    lines += [
        "",
        "**Recall per typology** (combined, test)",
        "",
        "| typology | units | unit recall | attempts | attempt recall |",
        "|---|---:|---:|---:|---:|",
    ]
    for t in typologies:
        lines.append(
            f"| {t.typology} | {t.units} | {t.unit_recall:.1%} | {t.attempts} "
            f"| {t.attempt_recall:.1%} |"
        )
    lines += [
        "",
        "**Alerts by triggered rule** (combined, test)",
        "",
        "| rule | alerts | precision |",
        "|---|---:|---:|",
    ]
    for r in rules:
        lines.append(f"| {r.rule_id} | {r.alerts:,} | {r.precision:.1%} |")
    return "\n".join(lines)


def main() -> None:
    settings = get_settings()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--frozen", action="store_true", help="reuse existing thresholds.json")
    parser.add_argument("--no-report", action="store_true")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s", datefmt="%H:%M:%S")

    split_date = settings.train_test_split_date
    budget = settings.alert_budget_per_1k_windows
    th_path = settings.thresholds_path
    conn = duckdb.connect(str(settings.duckdb_path))
    t0 = time.perf_counter()

    log.info("legs: %s", f"{build_legs(conn, split_date):,}")
    log.info("account-windows: %s", f"{build_features(conn):,}")
    log.info("anomaly scores: %s", f"{fit_and_score(conn, settings.anomaly_model_path):,}")

    # --- train-only tuning, then freeze ------------------------------------
    tuning = None
    if args.frozen:
        th = load_thresholds(th_path)
        log.info("using frozen thresholds %s", th_path)
    else:
        tuning = tune_thresholds(conn, split_date, budget)
        th = tuning.thresholds
        save_thresholds(th, th_path)
        log.info("tuned (%d trials): %s", tuning.trials, th.model_dump())
    sha = thresholds_sha256(th_path)
    log.info("thresholds sha256 %s", sha[:12])

    # --- detection uses only the frozen thresholds ---------------------------
    log.info("rule hits: %s", build_rule_hits(conn, th))
    score_windows(conn, th)
    log.info("alerts: %s", f"{build_alerts(conn, th):,}")

    # --- evaluation -----------------------------------------------------------
    build_positive_units(conn, split_date)
    slices = slice_conditions(split_date)
    variants = {
        "combined": "alerts",
        "rules_only": build_ablation_alerts(conn, "rule_score", budget),
        "anomaly_only": build_ablation_alerts(conn, "anomaly_pct", budget),
    }
    metrics = []
    for variant, table in variants.items():
        for name in ("train", "test", "test_w1") if variant == "combined" else ("test", "test_w1"):
            m = evaluate_slice(conn, table, variant, name, slices[name], split_date)
            metrics.append(m)
            log.info(
                "%s/%s: alerts=%d precision=%.3f recall=%.3f",
                variant, name, m.alerts, m.precision, m.recall,
            )  # fmt: skip
    typologies = typology_recall(conn, "alerts", slices["test"], split_date)
    rules = rule_breakdown(conn, "alerts", slices["test"])
    conn.close()
    log.info("done in %.0fs", time.perf_counter() - t0)

    if not args.no_report:
        write_block("alerts", render_report(sha, tuning, metrics, typologies, rules, str(th_path)))
        log.info("report written to %s", PROGRESS_PATH)


if __name__ == "__main__":
    main()
